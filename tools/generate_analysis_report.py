#!/usr/bin/env python3
"""Generate the Phase 0 complexity report from XenonAnalyse output.

Reads:
  --xex            the decrypted default.xex (only for size + SHA-256)
  --switch-tables  the TOML file XenonAnalyse wrote (detected jump tables)
  --log            XenonAnalyse stdout/stderr, saved by the workflow
  --exit-code      XenonAnalyse exit code

Writes a Markdown report to --output.

The TOML schema of XenonAnalyse's output is not documented in the XenonRecomp
README (the example lives in the Unleashed Recompiled repo), so this script is
deliberately schema-agnostic: it counts array-of-tables blocks (`[[...]]`) and
`address =` entries without assuming key names, and it always includes the raw
TOML in the artifact for a human to read.

What XenonAnalyse does NOT produce (marked TODO in the report, not invented):
  - Function-boundary counts / functions reachable only by pointer or vtable.
    Needs a XenonRecomp codegen run with a minimal TOML config.
  - Kernel/XAM import list. Needs parsing the XEX2 header import-library table.
  - Shader inventory. Needs XenosRecomp over the extracted game data, not the XEX.
"""

import argparse
import hashlib
import re
import sys
from pathlib import Path


def sha256_of(path: Path) -> str:
    h = hashlib.sha256()
    with path.open("rb") as f:
        for chunk in iter(lambda: f.read(1024 * 1024), b""):
            h.update(chunk)
    return h.hexdigest()


def count_jump_tables(toml_path: Path) -> dict:
    """Schema-agnostic counts over the switch-tables TOML."""
    if not toml_path.exists():
        return {"exists": False, "tables": 0, "addresses": 0, "lines": 0}
    text = toml_path.read_text(errors="replace")
    tables = len(re.findall(r"(?m)^\s*\[\[", text))
    addresses = len(re.findall(r"(?m)^\s*address\s*=", text))
    return {
        "exists": True,
        "tables": tables,
        "addresses": addresses,
        "lines": len(text.splitlines()),
    }


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--xex", required=True)
    ap.add_argument("--switch-tables", required=True)
    ap.add_argument("--log", required=True)
    ap.add_argument("--exit-code", required=True)
    ap.add_argument("--output", required=True)
    args = ap.parse_args()

    xex = Path(args.xex)
    tables_toml = Path(args.switch_tables)
    log = Path(args.log)
    output = Path(args.output)

    xex_size = xex.stat().st_size if xex.exists() else 0
    xex_sha = sha256_of(xex) if xex.exists() else "MISSING"
    jt = count_jump_tables(tables_toml)
    log_text = log.read_text(errors="replace") if log.exists() else ""
    log_tail = "\n".join(log_text.splitlines()[-40:])

    lines = []
    lines.append("# Child of Light — Phase 0 XEX analysis report")
    lines.append("")
    lines.append("Generated by `.github/workflows/analyze-xex.yml` (XenonAnalyse).")
    lines.append("")

    lines.append("## Input file")
    lines.append("")
    lines.append(f"- XEX size: **{xex_size:,} bytes** ({xex_size / 1024 / 1024:.1f} MiB)")
    lines.append(f"- XEX SHA-256: `{xex_sha}`")
    lines.append(f"- XenonAnalyse exit code: `{args.exit_code}`")
    lines.append("")

    lines.append("## Jump tables (measured by XenonAnalyse)")
    lines.append("")
    if not jt["exists"]:
        lines.append("- `switch_tables.toml` was **not produced**. XenonAnalyse failed or the")
        lines.append("  XEX is encrypted. See `xenonanalyse.log` in the artifact.")
    elif jt["tables"] == 0 and jt["addresses"] == 0:
        lines.append("- **0 jump tables detected** by stock XenonAnalyse.")
        lines.append("- This is the Rayman Origins case: stock detection found 0 there too,")
        lines.append("  and the project had to write its own simulation-based detector for")
        lines.append("  173 tables. Expect the same manual work here unless the TOML below")
        lines.append("  shows otherwise.")
    else:
        lines.append(f"- Array-of-tables blocks in the TOML: **{jt['tables']}**")
        lines.append(f"- `address =` entries in the TOML: **{jt['addresses']}**")
        lines.append(f"- TOML lines: {jt['lines']}")
        lines.append("- Read the raw `switch_tables.toml` in the artifact for the full list.")
    lines.append("")

    lines.append("## TODO — not measured by XenonAnalyse (do not guess)")
    lines.append("")
    lines.append("### Functions reachable only by pointer / vtable")
    lines.append("")
    lines.append("- TODO: run a XenonRecomp codegen pass with a minimal TOML config")
    lines.append("  (`XenonRecomp [config.toml] [ppc_context.h]`, see the XenonRecomp README)")
    lines.append("  and count functions without a `.pdata` entry. In Rayman Origins there")
    lines.append("  were 5,807 such functions plus 49 `mtctr`/`bdz` switches, all declared")
    lines.append("  by hand in the TOML.")
    lines.append("")
    lines.append("### Kernel / XAM imports")
    lines.append("")
    lines.append("- TODO: parse the XEX2 header import-library table (big-endian) and list")
    lines.append("  every imported library (xboxkrnl, xam, xbdm, ...) with its import count.")
    lines.append("  Reference for the XEX format: Xenia docs/wiki on the XEX container.")
    lines.append("  Until this is done, the set of kernel/XAM imports CoL needs is unknown.")
    lines.append("")
    lines.append("### Shader inventory")
    lines.append("")
    lines.append("- TODO: run XenosRecomp over the extracted game data (not the XEX alone)")
    lines.append("  and count vertex/pixel shaders. Compare with the UbiArt shader patterns")
    lines.append("  patched in Rayman Origins (`setp_inv`, relative constant addressing,")
    lines.append("  UbiArt vertex fetch, render-to-texture `Resolve`).")
    lines.append("")

    lines.append("## Verdict guidance")
    lines.append("")
    lines.append("- Few jump tables + imports already covered by ReXGlue = viable, proceed")
    lines.append("  to Phase 1 (project skeleton).")
    lines.append("- 0 jump tables detected + many unknown imports = same manual effort as")
    lines.append("  Rayman Origins (custom jump-table detector, hand-written function")
    lines.append("  boundaries). Still doable, but budget weeks of analysis before any build.")
    lines.append("- XenonAnalyse failing outright (encrypted XEX, unreadable file) = stop:")
    lines.append("  re-dump a decrypted `default.xex` first.")
    lines.append("")

    lines.append("## XenonAnalyse log (last 40 lines)")
    lines.append("")
    lines.append("```")
    lines.append(log_tail if log_tail else "(empty log)")
    lines.append("```")
    lines.append("")

    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text("\n".join(lines), encoding="utf-8")
    print(f"Wrote {output}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
